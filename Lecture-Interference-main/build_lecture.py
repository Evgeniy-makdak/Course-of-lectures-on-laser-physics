def draw_superposition():
    """Две волны: в фазе / в противофазе."""
    fig, axes = plt.subplots(2, 1, figsize=(7.2, 4.6), dpi=160)
    x = np.linspace(0, 4 * np.pi, 600)
    y1 = np.sin(x)
    y2_in = np.sin(x)
    y2_out = np.sin(x + np.pi)

    for ax, y2, title, sum_color in [
        (axes[0], y2_in, "В фазе: усиление (максимум)", "#2e7d32"),
        (axes[1], y2_out, "В противофазе: гашение (минимум)", "#c62828"),
    ]:
        ax.plot(x, y1, color="#1976d2", lw=1.6, alpha=0.85, label="волна 1")
        ax.plot(x, y2, color="#f57c00", lw=1.6, alpha=0.85, label="волна 2")
        ax.plot(x, y1 + y2, color=sum_color, lw=2.4, label="сумма")
        ax.axhline(0, color="#90a4ae", lw=0.8)
        ax.set_title(title, fontsize=11, fontweight="bold", pad=6)
        ax.set_xlim(0, 4 * np.pi)
        ax.set_ylim(-2.4, 2.4)
        ax.set_yticks([-2, -1, 0, 1, 2])
        ax.set_xticks([])
        ax.legend(loc="upper right", fontsize=8, framealpha=0.92)
        ax.grid(True, alpha=0.25)
        for spine in ax.spines.values():
            spine.set_color("#b0bec5")

    fig.suptitle("Принцип суперпозиции световых волн", fontsize=13, fontweight="bold", y=0.98)
    fig.tight_layout(rect=[0, 0, 1, 0.95])
    path = os.path.join(DIAG_DIR, "01_superposition.png")
    fig.savefig(path, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    return path


