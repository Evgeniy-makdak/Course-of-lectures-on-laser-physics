def draw_thin_lens_formula():
    W, H = 1000, 560
    img = Image.new("RGB", (W, H), "#1a1a2e")
    d = ImageDraw.Draw(img)
    f, fb = _font(18), _font(22, True)
    d.text((40, 30), "Формула тонкой линзы и увеличение", fill="#eeeeee", font=fb)
    lines = [
        ("1/F = 1/d + 1/f", "#80cbc4"),
        ("F — фокусное расстояние, d — до предмета, f — до изображения", "#b0bec5"),
        ("", "#eeeeee"),
        ("Оптическая сила: D = 1/F  (диоптрии)", "#ffab91"),
        ("Линейное увеличение: Γ = H'/H = − f/d", "#ffcc80"),
        ("|Γ| > 1 — увеличение; знак «−» — перевёрнутое действительное изображение", "#b0bec5"),
        ("", "#eeeeee"),
        ("Пример: F = 100 мм, d = 150 мм → 1/f = 1/F − 1/d → f = 300 мм", "#eeeeee"),
        ("Γ = −300/150 = −2  (изображение вдвое больше и перевёрнуто)", "#eeeeee"),
    ]
    y = 100
    for text, col in lines:
        d.text((50, y), text, fill=col, font=f if not text.startswith("1/F") else fb)
        y += 42
    return _save(img, "geo_thin_lens.png")


